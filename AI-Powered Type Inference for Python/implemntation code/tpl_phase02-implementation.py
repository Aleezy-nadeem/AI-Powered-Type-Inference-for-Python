# Function to extract features and actual variable types
def extract_features_from_file(path):
    with open(path, "r", encoding="utf-8", errors="ignore") as f:
        code = f.read()

    tree = ast.parse(code)

    features = {
        # AST nodes
        "FunctionDef": sum(isinstance(node, ast.FunctionDef) for node in ast.walk(tree)),
        "Assign": sum(isinstance(node, ast.Assign) for node in ast.walk(tree)),
        "If": sum(isinstance(node, ast.If) for node in ast.walk(tree)),
        "For": sum(isinstance(node, ast.For) for node in ast.walk(tree)),
        "While": sum(isinstance(node, ast.While) for node in ast.walk(tree)),
        "function_calls": sum(isinstance(node, ast.Call) for node in ast.walk(tree)),
        "num_assigned_vars": 0  # will count below
    }

    # Track variable types dynamically (simple static inference)
    assigned_vars = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    var_name = t.id
                    # Try to infer type from assigned value (simple static check)
                    value_node = node.value
                    if isinstance(value_node, ast.Constant):
                        var_type = type(value_node.value).__name__  # int, str, float, etc.
                    elif isinstance(value_node, ast.List):
                        var_type = "list"
                    elif isinstance(value_node, ast.Dict):
                        var_type = "dict"
                    elif isinstance(value_node, ast.Set):
                        var_type = "set"
                    elif isinstance(value_node, ast.Tuple):
                        var_type = "tuple"
                    else:
                        var_type = "unknown"

                    assigned_vars[var_name] = var_type

    features["num_assigned_vars"] = len(assigned_vars)

    # If multiple variables, take first variable type as target (can expand later)
    if assigned_vars:
        features["true_type"] = list(assigned_vars.values())[0]
    else:
        features["true_type"] = "unknown"

    return features

