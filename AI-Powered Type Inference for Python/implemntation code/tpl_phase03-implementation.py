import csv

RUNTIME_LOG = "runtime_types.csv"

def log_runtime_type(variable_name, value, project_id, file_name):
    row = {
        "project_id": project_id,
        "file_name": file_name,
        "variable_name": variable_name,
        "runtime_type": type(value).__name__
    }

    file_exists = os.path.exists(RUNTIME_LOG)

    with open(RUNTIME_LOG, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=row.keys())
        if not file_exists:
            writer.writeheader()
        writer.writerow(row)

