MEMORY_FILE = "type_memory.csv"

def store_feedback(project_id, file_name, variable_name,
                   predicted_type, corrected_type):
    row = {
        "project_id": project_id,
        "file_name": file_name,
        "variable_name": variable_name,
        "predicted_type": predicted_type,
        "corrected_type": corrected_type,
        "timestamp": datetime.now()
    }

    if os.path.exists(MEMORY_FILE):
        df_mem = pd.read_csv(MEMORY_FILE)
        df_mem = pd.concat([df_mem, pd.DataFrame([row])], ignore_index=True)
    else:
        df_mem = pd.DataFrame([row])

    df_mem.to_csv(MEMORY_FILE, index=False)
    print("✔ Feedback stored")

def project_bias_prediction(project_id):
    if not os.path.exists(MEMORY_FILE):
        return None

    df_mem = pd.read_csv(MEMORY_FILE)
    project_data = df_mem[df_mem["project_id"] == project_id]

    if project_data.empty:
        return None

    return project_data["corrected_type"].mode()[0]

def predict_type(features, model, label_encoder, project_id):
    bias = project_bias_prediction(project_id)

    if bias:
        return bias
    else:
        encoded = model.predict([features])[0]
        return label_encoder.inverse_transform([encoded])[0]

RETRAIN_THRESHOLD = 20

def should_retrain():
    if not os.path.exists(MEMORY_FILE):
        return False
    return len(pd.read_csv(MEMORY_FILE)) >= RETRAIN_THRESHOLD

def retrain_model(base_csv):
    print("🔁 Retraining model using feedback...")

    base_df = pd.read_csv(base_csv)
    feedback_df = pd.read_csv(MEMORY_FILE)

    if feedback_df.empty:
        return rf_model, le

    retrain_df = base_df.sample(
        n=min(len(feedback_df), len(base_df)),
        random_state=42
    ).copy()

    retrain_df["true_type"] = feedback_df["corrected_type"].values[:len(retrain_df)]

    combined_df = pd.concat([base_df, retrain_df], ignore_index=True)

    X_new = combined_df.drop(columns=["true_type"])
    y_new = le.fit_transform(combined_df["true_type"])

    model = RandomForestClassifier(n_estimators=100, random_state=42)
    model.fit(X_new, y_new)

    print("✔ Model retrained successfully")
    return model, le

